package ru.selfin.backend.model.enums;

/**
 * Характер плановой строки или категории — насколько известны заранее сумма и дата.
 *
 * <p>Канон — {@code docs/superpowers/specs/2026-09-01-product-rules.md}, раздел «Характер плановой
 * строки»; на экране — Обязательство / Ожидание / Хотелка, имена живут во
 * {@code frontend/src/lib/priority.ts}. Константы исторические и читаются как очерёдность — это не
 * очерёдность (ANO-173): переименование в коде и базе сочтено не стоящим цены.
 *
 * <p>В расчёте остатка характер не участвует — решение владельца 23.09.2026: план есть план.
 */
public enum Priority {
    /** Обязательство: сумма и дата известны заранее. */
    HIGH,
    /** Ожидание: мягкое планирование с допуском превышения — сумма примерная. Дефолт. */
    MEDIUM,
    /** Хотелка: мелкое «если влезет»; крупное идёт через экран хотелок. */
    LOW
}
