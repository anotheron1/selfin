package ru.selfin.backend.model.enums;

/**
 * Что сделать с деньгами при удалении копилки (ANO-86, спека
 * {@code 2026-09-12-fund-money-flow-design.md} §4.3).
 *
 * <p>Копилка — условное место, где деньги лежат. Поэтому при её удалении деньги НЕ обязаны
 * возвращаться: они могли быть потрачены на саму цель. Но удаление может быть и вынужденным,
 * и тогда деньги должны вернуться, а кармашек с остатком пересчитаться.
 *
 * <p>Обе трактовки законны, и выбрать за человека продукт не может — он спрашивает. До этой
 * правки он молча делал половину одного и половину другого: сумма исчезала из свободных
 * денег и оставалась раздувать капитал.
 */
public enum FundMoneyDisposal {

    /** Деньги возвращаются в свободные: обратный перевод на всю сумму, затем закрытие. */
    RETURN,

    /**
     * Деньги потрачены на цель. Копилка закрывается, перевод остаётся в журнале настоящей
     * тратой, а ликвид капитала падает на сумму: вещь куплена, в чистой стоимости этих денег
     * больше нет.
     */
    SPENT
}
