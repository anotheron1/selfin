-- ANO-215: план покупки из зафиксированной хотелки — бронь.
--
-- Конверсия хотелки в плановое событие заводила строку характером «Хотелка» (LOW). Хотелку с
-- прошедшей датой кармашек не держит (канон правил продукта, «Характер плановой строки»), и
-- решённая покупка через день после даты снова считалась свободными деньгами. Решение владельца
-- 03.10 (карта C1, Р11-А): такой план — бронь, как платёж по кредиту из той же конверсии
-- (ANO-188, V27). Новые конверсии заводят бронь сами (WishlistConversionService.buildPlanEvent);
-- здесь — уже заведённые.
--
-- План опознаётся по ссылке источника: converted_to_event_id хотелки-события или копилки.
-- Удалённый источник — тоже в счёт: ссылка остаётся, план по-прежнему решённая покупка.
--
-- Переводится только «Хотелка» — характер, который ставила конверсия. Если человек сменил
-- характер сам, его выбор не трогаем. Строка с экрана «Хотелки» (wishlist_status задан) всегда
-- «Хотелка» — её держит chk_wishlist_status_only_low. Артефактом конверсии она быть не может, но
-- если бы ссылка на неё нашлась, без условия на статус миграция упала бы на этом ограничении.
--
-- На стенде 03.10 такой план один — «Ноутбук»; у владельца 24.09 конверсий не было вовсе.
UPDATE financial_events e
   SET priority = 'HIGH', updated_at = CURRENT_TIMESTAMP
 WHERE e.priority = 'LOW'
   AND e.wishlist_status IS NULL
   AND (e.id IN (SELECT s.converted_to_event_id FROM financial_events s WHERE s.converted_to_event_id IS NOT NULL)
     OR e.id IN (SELECT f.converted_to_event_id FROM target_funds f WHERE f.converted_to_event_id IS NOT NULL));
