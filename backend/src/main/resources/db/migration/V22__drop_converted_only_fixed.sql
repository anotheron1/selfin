-- ANO-103: вернуть сконвертированной хотелке право уйти в OPEN/DISMISSED.
--
-- Ограничения chk_event_converted_only_fixed и chk_fund_converted_only_fixed завела
-- миграция V18. Коммит f26ea93 от 17.06.2026 убрал их из ТЕКСТА V18 — то есть правил
-- уже применённую миграцию. Flyway применённые версии не перезапускает, а контрольная
-- сумма в flyway_schema_history оказалась подогнана под новый текст (CRC текущего файла
-- V18 = -202518422 и ровно это значение лежит в истории), поэтому `flyway validate`
-- молчит и расхождение ничем не обнаруживается.
--
-- Итог: базы, созданные ДО 17.06.2026, ограничения по-прежнему несут; базы, собранные
-- из текущих файлов, — нет. Проверено на стенде 12.09.2026: в `selfin` оба ограничения
-- есть, в базе, собранной из текущих миграций, их нет. Поэтому ANO-103 не воспроизводится
-- ни одним тестом на Testcontainers: он поднимает свежую базу, где запрещать уже нечему.
--
-- DROP ... IF EXISTS: на свежей базе no-op, на старой — собственно починка. Форма выбрана
-- так, чтобы к ней нечего было доделывать при появлении колонки владельца (ANO-146):
-- ограничение снимается целиком, а не переписывается под новый набор колонок.
ALTER TABLE financial_events DROP CONSTRAINT IF EXISTS chk_event_converted_only_fixed;
ALTER TABLE target_funds     DROP CONSTRAINT IF EXISTS chk_fund_converted_only_fixed;
