-- ANO-91: recurring_rule_id — поле ПЛАНА, не факта.
--
-- До этой правки FinancialEventService.createLinkedFact копировал ссылку на правило из
-- родительского плана в факт. Факт садился на тот же ключ (recurring_rule_id, date), что его
-- собственный родитель, и упирался в уникальный индекс uq_events_rule_date_active (V16) —
-- отметить оплаченными аренду, ипотеку и подписки было нельзя, приходила пятисотка.
--
-- Наследование убрано в коде. Эта миграция чистит то, что успело записаться раньше: факт с
-- ссылкой на правило проходил вставку в одном случае — когда его дата НЕ совпадала с датой
-- родительского плана. Такие строки не падали, но тихо участвовали в состоянии правила:
-- findExecutedDatesByRule и findMaxExecutedDateByRule фильтруют по status='EXECUTED' и НЕ
-- смотрят на event_kind, поэтому факт попадал в множество исполненных дат правила и подавлял
-- генерацию плана на свою дату. В RecurringRuleService:150 против этого уже стоял защитный
-- клэмп с комментарием «lastExec раньше startDate возможен у FACT с ручной датой» — симптом
-- лечили, причину нет.
--
-- На тестовом стенде таких строк ноль (331 PLAN с правилом, 0 фактов), но на базе, прожившей
-- дольше, они могли остаться. Миграция идемпотентна и на чистой базе — no-op.
--
-- Форма под мультиюзер (ANO-146): это UPDATE по event_kind, колонки владельца не касается —
-- когда она появится, переделывать здесь нечего.
UPDATE financial_events
   SET recurring_rule_id = NULL
 WHERE event_kind = 'FACT'
   AND recurring_rule_id IS NOT NULL;
