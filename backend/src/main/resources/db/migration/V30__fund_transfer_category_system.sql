-- ANO-224: «Переводы в копилки» — системная категория, как «Хотелки», «Кредит» и «Цели».
--
-- Продукт пишет в неё каждый перевод в копилку и находит её по имени. Несистемную человек удалял в
-- «Настройках», а имя уникально во всей таблице, вместе с удалёнными: продукт искал только живую, не
-- находил, заводил вторую — и вставка падала, каждый перевод отвечал 409. Теперь продукт возвращает
-- удалённую сам (CategoryService.systemCategory); здесь — то же для старых баз: удалённая
-- возвращается, живая становится системной — «Настройки» перестают предлагать удаление и правку.
-- Тип — расходы, без признака основного дохода (иначе тип не сохранить: chk_primary_income_only_income),
-- прогноз выключен — выключателя у системной категории на экране нет. Категории нет — миграция её не
-- заводит: продукт заведёт при первом переводе.
-- Спека: docs/superpowers/specs/2026-10-11-transfer-category-revive-design.md
UPDATE categories
   SET is_deleted = FALSE, is_system = TRUE, type = 'EXPENSE', primary_income = FALSE, forecast_enabled = FALSE
 WHERE name = 'Переводы в копилки';
