-- V19: флаг «основной доход» на категории (ANO-35)
--
-- Горизонт кармашка «до дохода» брал БЛИЖАЙШИЙ плановый доход любой категории.
-- Мелкий нерегулярный приход (возврат долга, кэшбек) схлопывал горизонт до пары
-- дней и делал число оптимистичным. Флаг отмечает категории, приход по которым
-- считается настоящим «следующим доходом» (зарплата, аванс).
--
-- Дефолт FALSE: пока ни одна категория не отмечена, поведение прежнее — берётся
-- любой доход (обратная совместимость и работающий кармашек у новых пользователей).

ALTER TABLE categories ADD COLUMN primary_income BOOLEAN NOT NULL DEFAULT FALSE;

-- Флаг осмыслен только для доходных категорий.
ALTER TABLE categories ADD CONSTRAINT chk_primary_income_only_income
    CHECK (primary_income = FALSE OR type = 'INCOME');
