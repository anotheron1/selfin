-- Найдено ручным тестированием ANO-50, блок A2, на чистом стенде.
--
-- Правится миграцией, а не правкой V15: та уже накатана везде, её контрольная сумма менять
-- нельзя. На свежей базе V15 включит флаг, V21 тут же снимет — итоговое состояние верное.
--
-- Выключается ВЕЗДЕ, а не только у засеянных категорий: решение владельца от 5 сентября 2026.
-- Механизм прогноза пересматривается отдельно после тестового запуска; до тех пор он не
-- должен работать по умолчанию ни у кого. Пользователь может включить его вручную на экране
-- категорий — этот путь остаётся и миграцией не затрагивается.
