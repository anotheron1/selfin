#!/bin/sh
# Обновление сервера (шаг 5 плана спринта 6): сначала копия — миграции меняют данные. Копия не прошла — обновления нет.
# Тег образов — SELFIN_TAG в .env: sha-<коммит>, у которого опубликованы оба образа (план, шаг 6). Выкатка кнопкой
# (deploy/release.sh, ANO-246) пишет тег и зовёт этот же скрипт.
# Для обновлений уже работающего сервера; первая установка — docker compose up -d: копий до неё не было, делать нечего.
# Копия — в отдельном контейнере (run, а не exec): проходит, даже если контейнер расписания остановлен.
set -eu
cd "$(dirname "$0")"
docker compose run --rm -T backup backup
docker compose pull
docker compose up -d --build
