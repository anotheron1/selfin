/**
 * Ключ попытки записи (ANO-192).
 *
 * Сервер не записывает второй раз запрос с уже виденным `Idempotency-Key`. Этого мало, если
 * ключ рождается на каждое нажатие: ответ потерялся — сервер записал, а телефон не узнал, —
 * человек жмёт снова, и повтор приходит с новым ключом. Так было до ANO-192: у брони на 192 ₽
 * два касания кружка дали «факт 384 ₽».
 *
 * Поэтому ключ живёт, пока человек повторяет ту же запись:
 *   * та же цель и те же данные — тот же ключ: сервер вернёт уже записанное;
 *   * данные другие — ключ новый, а прежний забыт. Иначе сервер вернул бы первую запись,
 *     и новый ввод молча пропал бы. Лишняя запись видна в журнале, пропавшая — никому;
 *   * запись удалась — ключ забыт: следующая такая же — новая. Две одинаковые покупки за день —
 *     два факта.
 *
 * Цель — куда пишется: факт к этому плану, факт без плана, план из быстрого ввода, перевод в эту
 * копилку. У каждой цели одна незавершённая попытка.
 *
 * Спека: docs/superpowers/specs/2026-09-27-write-attempt-key-design.md
 */
export class AttemptKeys {
    private readonly pending = new Map<string, { data: string; key: string }>();

    constructor(private readonly newKey: () => string = () => crypto.randomUUID()) {}

    /** Ключ записи в цель `target` с данными `data`. */
    keyFor(target: string, data: unknown): string {
        const json = JSON.stringify(data);
        const attempt = this.pending.get(target);
        if (attempt?.data === json) return attempt.key;
        const key = this.newKey();
        this.pending.set(target, { data: json, key });
        return key;
    }

    /**
     * Запись с ключом `key` удалась: её попытка закончена. Если попытку цели уже заменила более
     * новая — две записи наложились, — её ключ остаётся (ревью #104): иначе повтор новой после
     * потерянного ответа пришёл бы с новым ключом.
     */
    done(target: string, key: string): void {
        if (this.pending.get(target)?.key === key) this.pending.delete(target);
    }
}

/**
 * Попытки приложения — одна память на все экраны: повтор записи факта из журнала и из листа
 * «Записать факт» — одна попытка. Живёт до перезагрузки страницы.
 */
export const attempts = new AttemptKeys();
