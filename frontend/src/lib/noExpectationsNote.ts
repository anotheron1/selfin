import type { PocketResponse } from '../types/api';

/**
 * Оговорка к кармашку, когда в плане до конца горизонта нет ни одного ожидания (ANO-185).
 *
 * Люди недооценивают будущие траты: без продуктов, бензина и кафе в плане кармашек завышен
 * по построению. Строка говорит об этом честно — не «посчитаем точнее» (запрет 3), а «число
 * неполное», и без упрёка (правило 12).
 *
 * Когда прогноз научился, строки нет: «N — с обычными тратами» показывает честное число сам,
 * и два сообщения об одном под одним числом не нужны (решение владельца 24.09, вариант А).
 * Прогноз, равный нулю, — тоже прогноз: его строка на экране есть.
 *
 * Спека: docs/superpowers/specs/2026-09-24-no-expectations-line-design.md
 */
export function noExpectationsNote(
    p: Pick<PocketResponse, 'planHasExpectations' | 'pocketWithForecast'>,
): string | null {
    if (p.planHasExpectations || p.pocketWithForecast != null) return null;
    return 'В плане нет ожиданий — продукты, бензин, кафе. Пока их нет, число выше, чем будет на деле.';
}
