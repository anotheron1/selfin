/**
 * Номера запросов по строке — чтобы применить только ответ на последний (ANO-105).
 *
 * Пересчётов по строке примерки бывает несколько подряд: ползунок «Когда» двигают дальше, пока
 * сервер отвечает на прошлое положение. Ответы приходят в любом порядке, и ответ старого запроса
 * после ответа нового показал бы график другой даты под ползунком этой.
 */
export class LatestRequests {
    private readonly last: Record<string, number> = {};

    /** Новый запрос строки: его номер. */
    start(key: string): number {
        this.last[key] = (this.last[key] ?? 0) + 1;
        return this.last[key];
    }

    /** Ответ на запрос с этим номером — последний ли он для строки. */
    isLatest(key: string, n: number): boolean {
        return this.last[key] === n;
    }
}
