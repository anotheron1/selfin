/**
 * Слова копилки на счёте — одни на карточке «Целей» и в выборе счёта (ANO-164, ANO-174).
 *
 * Привязка к счёту — ярлык, а не перемещение денег (ANO-158): «накоплено» становится остатком
 * счёта, перевод в копилку запрещён — он записал бы те же рубли второй раз. А уже переведённое в
 * конверт, пока копилка на счёте, не считается ни в накопленном, ни в капитале; отвязка возвращает
 * его. Замер 29.09: 1 000 в конверте, привязка к карте — накоплено 53 900, капитал −1 000.
 */

export const ON_ACCOUNT = 'Накопленное берётся с остатка счёта.';

/** Почему у копилки на счёте нет «Пополнить» — и что делать вместо. Та же строка на карточке. */
export const NO_TRANSFER = 'Пополнять переводом нельзя — двигай деньги на счёте и обновляй его остаток.';

export const ENVELOPE = 'Копилка держит свой баланс и пополняется переводом из свободных денег.';

/**
 * Строки подсказки у выбора счёта.
 *
 * @param p.linked        выбран счёт
 * @param p.wasLinked     копилка была на счёте до правки; у новой — нет
 * @param p.holdsOwnMoney в копилке лежат деньги — смысл имеет, только пока она конверт
 */
export function fundAccountHint(p: { linked: boolean; wasLinked: boolean; holdsOwnMoney: boolean }): string[] {
    if (p.linked) {
        return p.wasLinked || !p.holdsOwnMoney
            ? [ON_ACCOUNT, NO_TRANSFER]
            : [ON_ACCOUNT, NO_TRANSFER,
                'То, что уже переведено в копилку, пока она на счёте, не входит ни в накопленное, ни в капитал — '
                + 'вернётся, если отвязать.'];
    }
    return p.wasLinked
        ? [ENVELOPE, 'Накопленное снова покажет только то, что в неё переводили.']
        : [ENVELOPE];
}
