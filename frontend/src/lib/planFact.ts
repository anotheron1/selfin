/**
 * Разница факта и плана — как есть (ANO-123, правило 12).
 *
 * Прежде здесь жил знак «в пользу пользователя» и цвет к нему (ANO-32): перерасход красный,
 * экономия зелёная, у дохода наоборот. Это оценка: превышенное ожидание не краснеет и не
 * считается провалом — оно становится новым числом (канон правил продукта, «Характер плановой
 * строки»). Без цвета знак «в пользу» остался бы той же оценкой, только незаметнее, поэтому
 * ушёл и он: разница — факт минус план для дохода и расхода одинаково.
 */

/**
 * Знак разницы «факт − план»: «+» — факта больше плана, «−» — меньше, пусто — ровно.
 * Минус обязателен: без него меньшее читается как прибавка.
 */
export function differenceSign(difference: number): string {
    return difference > 0 ? '+' : difference < 0 ? '−' : '';
}
